let openingIndex = null;

function buildIndex() {
  openingIndex = new Map();
  for (const [eco, name, moves] of OPENINGS) openingIndex.set(moves, { eco, name });
}

// Finds the most specific named opening for a list of SAN moves.
export function identifyOpening(sanMoves) {
  if (!openingIndex) buildIndex();
  let found = null;
  const clean = sanMoves.map((m) => m.replace(/[+#!?]/g, ''));
  // Longest prefix wins; also allow the check-stripped form to match lines like "Bb5+".
  for (let n = Math.min(clean.length, 16); n >= 1; n--) {
    const prefix = clean.slice(0, n).join(' ');
    const withChecks = sanMoves.slice(0, n).map((m) => m.replace(/[#!?]/g, '')).join(' ');
    found = openingIndex.get(withChecks) || openingIndex.get(prefix) || null;
    if (found) break;
  }
  return found;
}
